export function randomRomanticQuote(exclude?: string | null): string {
  if (ROMANTIC_QUOTES_MM.length <= 1) return ROMANTIC_QUOTES_MM[0];
  let next = ROMANTIC_QUOTES_MM[Math.floor(Math.random() * ROMANTIC_QUOTES_MM.length)];
  let guard = 0;
  while (next === exclude && guard < 8) {
    next = ROMANTIC_QUOTES_MM[Math.floor(Math.random() * ROMANTIC_QUOTES_MM.length)];
    guard++;
  }
  return next;
}
